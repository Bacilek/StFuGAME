#!/usr/bin/env node
// Expedition journal analysis: node scripts/expedition_stats.js [--since YYYY-MM-DD] [--out roster/expedition-report.md]
// Reads logs/expeditions.jsonl + roster/*/logs/expeditions.jsonl (local only, gitignored) and prints a markdown report.
// How to read it and what we learned so far: docs/expedition-analysis.md.
const fs = require("fs");
const path = require("path");

const args = process.argv.slice(2);
const opt = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const since = opt("--since") || "0000";
const outFile = opt("--out");

const root = path.join(__dirname, "..");
const files = [path.join(root, "logs", "expeditions.jsonl")];
const rosterDir = path.join(root, "roster");
if (fs.existsSync(rosterDir)) {
  for (const d of fs.readdirSync(rosterDir)) {
    const f = path.join(rosterDir, d, "logs", "expeditions.jsonl");
    if (fs.existsSync(f)) files.push(f);
  }
}

// The journal names an unmapped mission by its target item; map those onto the real mission names.
const ALIAS = {
  Barkeeper: "Running Dry", RidingStan: "Beak to Tail", Merman: "Plenty of Men in the Sea",
  Klaus: "Build A Friend", Unknown: "Unknown",
};
const TIER = {
  "Podium Climber": "S", "Dragon Taming": "S",
  "Hot Carnal Craving": "A", "Unicorn Whisperer": "A", "Build A Friend": "A",
};
const missionName = (raw) => {
  const n = raw.replace(/ \((bonus unverified|unknown mission)\)/, "").trim();
  return ALIAS[n] || n;
};

const rows = [];
for (const f of files) {
  const who = f.includes(`${path.sep}roster${path.sep}`) ? path.basename(path.dirname(path.dirname(f))) : "main";
  for (const line of fs.readFileSync(f, "utf8").split("\n")) {
    if (!line.trim()) continue;
    let j; try { j = JSON.parse(line); } catch { continue; }
    if ((j.started || "") < since) continue;
    j.who = who; j.name = missionName(j.mission || "?");
    j.ok = j.heroism >= 40;
    // picks: "3: [Item(+h, future x), ...] → Picked"
    j.rounds = (j.picks || []).map((p) => {
      const m = p.match(/^(\d+): \[(.*)\] → (.*)$/);
      if (!m) return null;
      const items = [...m[2].matchAll(/(\w+)\(([+-]?\d+)/g)].map((x) => ({ id: x[1], h: +x[2] }));
      return { n: +m[1], items, pick: m[3].trim() };
    }).filter(Boolean);
    rows.push(j);
  }
}

const out = [];
const P = (s = "") => out.push(s);
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(0) + " %" : "–");
const avg = (a) => (a.length ? (a.reduce((x, y) => x + y, 0) / a.length).toFixed(1) : "–");
const table = (head, body) => { P("| " + head.join(" | ") + " |"); P("|" + head.map(() => "---").join("|") + "|"); body.forEach((r) => P("| " + r.join(" | ") + " |")); P(); };

P(`# Expedition report (${rows.length} expeditions, ${files.length} journals, since ${since})`);
P();
P("Generated by `scripts/expedition_stats.js`. `ok` = final heroism ≥ 40 (the 3-star maximum reward).");
P();

// 1. per mission
P("## Per mission");
const by = {};
for (const r of rows) (by[r.name] ||= []).push(r);
const order = Object.keys(by).sort((a, b) => (TIER[a] || "B").localeCompare(TIER[b] || "B") || by[b].length - by[a].length);
table(["mission", "tier", "n", "ok", "avg heroism", "min", "avg keys", "avg chests", "ok but > 45 (waste)"],
  order.map((k) => {
    const v = by[k];
    return [k, TIER[k] || "B", v.length, pct(v.filter((r) => r.ok).length, v.length), avg(v.map((r) => r.heroism)),
      Math.min(...v.map((r) => r.heroism)), avg(v.map((r) => r.keys)), avg(v.map((r) => r.chests)),
      pct(v.filter((r) => r.heroism > 45).length, v.length)];
  }));

// 2. failures: what went wrong
P("## Failed expeditions (< 40)");
const failed = rows.filter((r) => !r.ok);
P(`${failed.length} of ${rows.length} (${pct(failed.length, rows.length)}); full pick lists only with --failures, otherwise the last 12.`);
for (const r of args.includes("--failures") ? failed : failed.slice(-12)) {
  P(`- ${r.started} ${r.who} – **${r.name}** ended ${r.heroism} (target ${r.target}); picks: ` +
    r.rounds.map((x) => `${x.n}:${x.pick}`).join(", "));
}
P();

// 3. offers per round: number of options, and how Cake/CupCake change it
P("## Options on offer per round");
const sizes = {}; let afterCake = [], afterCup = [], afterOther = [];
for (const r of rows) r.rounds.forEach((x, i) => {
  (sizes[x.n] ||= []).push(x.items.length);
  if (i > 0 && x.n !== 6) { // round 6 follows a boss/wait, offer size independent of the previous pick
    const prev = r.rounds[i - 1].pick;
    (prev === "Cake" ? afterCake : prev === "CupCake" ? afterCup : afterOther).push(x.items.length);
  }
});
table(["round", "avg options", "share with 3", "share with 2", "share with 1"],
  Object.keys(sizes).sort((a, b) => a - b).map((n) => [n, avg(sizes[n]), pct(sizes[n].filter((s) => s === 3).length, sizes[n].length),
    pct(sizes[n].filter((s) => s === 2).length, sizes[n].length), pct(sizes[n].filter((s) => s === 1).length, sizes[n].length)]));
P(`Options in the round after picking: suckling pig (Cake) avg ${avg(afterCake)} (n=${afterCake.length}); chicken drumstick (CupCake) avg ${avg(afterCup)} (n=${afterCup.length}); anything else avg ${avg(afterOther)} (n=${afterOther.length}).`);
P();

// 3b. what a Cake / CupCake costs: the next round is restricted to 1 / 2 options
P("## Value of the round after a restricted pick");
const nxt = { Cake: [], CupCake: [], other: [] }, forced = {};
for (const r of rows) r.rounds.forEach((x, i) => {
  if (i === 0 || x.n === 6 || !x.items.length) return; // round 6 follows the boss/wait
  const prev = r.rounds[i - 1].pick, k = prev === "Cake" ? "Cake" : prev === "CupCake" ? "CupCake" : "other";
  const best = Math.max(...x.items.map((i) => i.h));
  nxt[k].push({ best, avg: x.items.reduce((a, b) => a + b.h, 0) / x.items.length, n: x.items.length });
  if (k === "Cake") for (const it of x.items) forced[it.id] = (forced[it.id] || 0) + 1;
});
table(["previous pick", "rounds", "avg options", "avg best option (points)", "avg points of an option"],
  Object.entries(nxt).map(([k, v]) => [k, v.length, avg(v.map((x) => x.n)), avg(v.map((x) => x.best)), avg(v.map((x) => x.avg))]));
P("Single option offered after a suckling pig (forced pick): " + Object.entries(forced).sort((a, b) => b[1] - a[1]).slice(0, 8).map(([k, v]) => k + " " + pct(v, nxt.Cake.length)).join(", "));
P();
// 3c. chain follow-up: after taking step k, how often is step k+1 on offer in the next round(s)?
P("## Chain follow-up (is the next step offered after taking one?)");
const CHAINS = {
  "Build A Friend": ["Hand", "Feet", "Body", "Klaus"], "Podium Climber": ["SmallHurdle", "BigHurdle", "WinnersPodium"],
  "Dragon Taming": ["Bait", "Dragon"], "Extinguished Fire": ["CampFire", "Phoenix", "BurntCampfire"],
  "Unicorn Whisperer": ["UnicornHorn", "Donkey", "Rainbow", "Unicorn"], "The Sword Trial": ["SwordInStone", "BentSword", "BrokenSword"],
  "Revealing Lady": ["Socks", "ClothPile", "RevealingCouple"], "Bewitched Stew": ["Well", "Girl", "Balloons"],
  "Running Dry": ["Mugs", "DraftBeer", "Barkeeper"], "Toxic Fountain Cure": ["Prince", "RoyalFrog"],
  "Plenty of Men in the Sea": ["FishingRod", "FishingBait", "Merman"], "Beak to Tail": ["Chicken", "Tiger", "RidingStan"],
  "Key + Treasure chest": ["Key", "Suitcase"],
};
const fu = [];
for (const [cname, ch] of Object.entries(CHAINS)) {
  let n = 0, next1 = 0, next2 = 0, ownN = 0, own1 = 0;
  for (const r of rows) r.rounds.forEach((x, i) => {
    const k = ch.indexOf(x.pick);
    if (k < 0 || k === ch.length - 1) return;
    const a = r.rounds[i + 1], b = r.rounds[i + 2];
    if (!a) return;
    const has = (rd) => rd && rd.items.some((it) => it.id === ch[k + 1]);
    n++; if (has(a)) next1++; if (has(a) || has(b)) next2++;
    if (r.name === cname) { ownN++; if (has(a)) own1++; }
  });
  fu.push([cname, ch.join(" → "), n, pct(next1, n), pct(next2, n), pct(own1, ownN) + " (n=" + ownN + ")"]);
}
table(["chain", "steps", "steps taken", "next step offered next round", "within 2 rounds", "same, when it is the main mission"], fu);

// 4. how often each encounter is offered / picked, per expedition
P("## Encounter frequency (per expedition, all missions)");
const off = {}, pk = {};
for (const r of rows) {
  const seen = {};
  for (const x of r.rounds) {
    for (const it of x.items) { off[it.id] ||= { n: 0, h: it.h }; off[it.id].n++; }
    pk[x.pick] = (pk[x.pick] || 0) + 1;
  }
}
const slots = rows.reduce((a, r) => a + r.rounds.reduce((b, x) => b + x.items.length, 0), 0);
table(["encounter", "points", "offered/expedition", "share of all slots", "picked/expedition"],
  Object.entries(off).sort((a, b) => b[1].n - a[1].n).map(([id, v]) => [id, v.h, (v.n / rows.length).toFixed(2), pct(v.n, slots), ((pk[id] || 0) / rows.length).toFixed(2)]));

// 5. keys and chests
P("## Keys and chests");
const withKey = rows.filter((r) => r.keys > 0);
P(`- Expeditions with ≥ 1 key picked: ${pct(withKey.length, rows.length)}; keys that became a chest: ${pct(rows.reduce((a, r) => a + r.chests, 0), rows.reduce((a, r) => a + r.keys, 0))}.`);
P(`- Avg keys / chests per expedition: ${avg(rows.map((r) => r.keys))} / ${avg(rows.map((r) => r.chests))} (limit 2×).`);
P(`- Avg heroism lost when the bot took a key instead of a point item is not measurable here; see "ok but > 45" above for over-farming.`);
P();

// 6. rewards
P("## Rewards after the boss");
const rw = {};
for (const r of rows) for (const x of r.rewards || []) { const k = x.replace(/[\d.]+$/, "").trim(); (rw[k] ||= []).push(x); }
table(["reward", "count", "share"], Object.entries(rw).sort((a, b) => b[1].length - a[1].length)
  .map(([k, v]) => [k, v.length, pct(v.length, rows.reduce((a, r) => a + (r.rewards || []).length, 0))]));

// 7. points sources: where does the heroism of a successful run come from?
P("## Where heroism comes from (ok expeditions)");
const src = {};
for (const r of rows.filter((r) => r.ok)) for (const x of r.rounds) {
  const it = x.items.find((i) => i.id === x.pick); if (!it) continue;
  src[x.pick] = (src[x.pick] || 0) + it.h;
}
const tot = Object.values(src).reduce((a, b) => a + b, 0);
table(["encounter picked", "points (sum)", "share"], Object.entries(src).sort((a, b) => b[1] - a[1]).slice(0, 15).map(([k, v]) => [k, v, pct(v, tot)]));
P("(Task bonuses credited at the end, e.g. +5 per dragon, are not in this table; only the point value shown on the pick.)");

const text = out.join("\n") + "\n";
if (outFile) { fs.mkdirSync(path.dirname(path.resolve(outFile)), { recursive: true }); fs.writeFileSync(outFile, text); console.log("wrote " + outFile); }
else process.stdout.write(text);
